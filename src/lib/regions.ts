/**
 * 전국 법정동코드(시군구 5자리) 사전.
 *
 * - 코드는 행정안전부 법정동코드 앞 5자리이며 국토교통부 실거래가 API 의 `LAWD_CD` 파라미터로 그대로 쓴다.
 * - lat/lon 은 시군구 청사 부근의 대표 좌표로, 지도 표시에만 쓴다(행정경계가 아니다).
 * - tier 는 지도에서 원 크기와 기본 분석 대상 선정에 쓴다.
 *
 * 참고: 2024년 전북특별자치도 출범으로 전라북도 코드가 45xxx → 52xxx 로 바뀌었다.
 *       강원특별자치도(51xxx)는 코드가 유지됐다.
 */

export type RegionTier = 'metro' | 'major' | 'mid' | 'small';

export interface SigunguInfo {
  /** 법정동코드 앞 5자리 */
  code: string;
  /** 시도 전체 명 */
  sido: string;
  /** 시도 축약 명 */
  sidoShort: string;
  /** 시군구 명 */
  name: string;
  /** 대표 위도 */
  lat: number;
  /** 대표 경도 */
  lon: number;
  /**
   * metro: 서울·광역시 자치구 및 수도권 핵심
   * major: 인구 50만 이상 대도시 / 도청소재지
   * mid:   인구 10만~50만 중소도시
   * small: 그 외 군 단위
   */
  tier: RegionTier;
}

/** 축약 생성자 — 목록을 읽기 쉽게 유지하기 위한 것 */
const R = (
  code: string,
  sido: string,
  sidoShort: string,
  name: string,
  lat: number,
  lon: number,
  tier: RegionTier,
): SigunguInfo => ({ code, sido, sidoShort, name, lat, lon, tier });

