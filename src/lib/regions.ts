export function regionLabel(code: string): string {
  const r = BY_CODE.get(code);
  return r ? `${r.sidoShort} ${r.name}` : code;
}

/** 이름으로 시군구 검색 (설정 화면 자동완성용) */
export function searchSigungu(query: string, limit = 20): SigunguInfo[] {
  const q = query.trim().replace(/\s+/g, '');
  if (!q) return [];
  return ALL_SIGUNGU.filter(
    (r) => `${r.sidoShort}${r.name}`.replace(/\s+/g, '').includes(q) || r.code.startsWith(q),
  ).slice(0, limit);
}

