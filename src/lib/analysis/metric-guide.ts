/**
 * 과열 지표 구성 요소의 "지금 이 값이 무슨 뜻인가" 해설.
 *
 * 숫자만 보여주면 100인지 108인지가 어떤 차이인지 알 수 없다.
 * 값의 구간별 의미 + 최근 변화 방향(추세) + 갈아타기 관점의 시사점을 함께 만든다.
 */

import type { MarketSentiment } from '@/lib/types';
import { formatPct } from '@/lib/format';

export interface MetricGuide {
  /** 구간 이름 (예: "매수우위") */
  level: string;
  /** 값이 뜻하는 것 */
  meaning: string;
  /** 최근 변화 방향 해설 */
  trend: string;
  /** 갈아타기 관점의 시사점 */
  implication: string;
  /** 값이 놓인 위치 0~1 (게이지 표시용) */
  position: number;
  /** 구간 경계 설명 */
  scale: string;
}

/** 매매수급지수 — 100 초과면 매수자가 더 많다는 뜻 */
export function supplyDemandGuide(s: MarketSentiment): MetricGuide {
  const v = s.supplyDemandIndex;
  const d = s.supplyDemandChange;

  const level =
    v >= 110
      ? '강한 매수우위'
      : v >= 100
        ? '매수우위'
        : v >= 90
          ? '균형'
          : v >= 80
            ? '매도우위'
            : '강한 매도우위';

  const meaning =
    v >= 110
      ? '사려는 사람이 팔려는 사람보다 뚜렷하게 많습니다. 호가가 잘 안 내려가고 매도자가 협상에서 우위입니다.'
      : v >= 100
        ? '매수 문의가 매도 물량보다 조금 많습니다. 급매가 빠르게 소화되기 시작하는 구간입니다.'
        : v >= 90
          ? '매수와 매도가 팽팽합니다. 개별 물건의 조건이 가격을 가르는 구간입니다.'
          : v >= 80
            ? '팔려는 사람이 더 많습니다. 매수자가 가격을 깎기 좋은 구간입니다.'
            : '매물이 쌓이고 매수 문의가 끊긴 상태입니다. 거래 자체가 잘 성사되지 않습니다.';

  const trend =
    Math.abs(d) < 0.3
      ? '전주와 거의 같아 방향 전환 신호는 아직 없습니다.'
      : d > 0
        ? `전주 대비 ${formatPct(d, 1)} 올라 매수 심리가 살아나는 중입니다. 지수는 가격보다 2~3개월 앞서 움직입니다.`
        : `전주 대비 ${formatPct(d, 1)} 내려 매수 심리가 식는 중입니다. 이 흐름이 4주 이상 이어지면 가격에 반영되기 시작합니다.`;

  const implication =
    v >= 100
      ? '상급지부터 호가가 오르는 구간입니다. 갈아타기를 미룰수록 갭이 벌어집니다.'
      : v >= 90
        ? '아직 방향이 정해지지 않았습니다. 지수가 100을 넘어서는지 4주 정도 지켜볼 만합니다.'
        : '매수자 우위 구간이라 상급지 급매를 잡기 좋습니다. 다만 내 집도 잘 안 팔린다는 점을 함께 계산해야 합니다.';

  return {
    level,
    meaning,
    trend,
    implication,
    position: Math.max(0, Math.min(1, (v - 70) / 60)),
    scale: '70(극심한 매도우위) ─ 100(균형) ─ 130(극심한 매수우위)',
  };
}

/** 신고가 비중 — 최근 거래 중 과거 최고가를 갱신한 비율 */
export function newHighGuide(s: MarketSentiment): MetricGuide {
  const v = s.newHighRatio;

  const level =
    v >= 20
      ? '과열'
      : v >= 10
        ? '상승 확산'
        : v >= 4
          ? '회복 초기'
          : v >= 1
            ? '바닥 다지기'
            : '침체';

  const meaning =
    v >= 20
      ? '최근 거래 5건 중 1건 이상이 그 단지 역대 최고가입니다. 추격 매수가 붙은 전형적인 과열 신호입니다.'
      : v >= 10
        ? '신고가가 꾸준히 나오고 있습니다. 특정 단지가 아니라 지역 전체로 상승이 번지는 구간입니다.'
        : v >= 4
          ? '일부 대장 단지에서만 신고가가 나옵니다. 상승 초입에 흔히 보이는 모습입니다.'
          : v >= 1
            ? '신고가가 드뭅니다. 저점에서 거래가 이뤄지지만 아직 가격을 밀어올리지는 못합니다.'
            : '신고가가 거의 없습니다. 직전 고점 대비 낮은 가격대에서만 거래됩니다.';

  const trend =
    v >= 10
      ? '이 비중이 20%를 넘으면 정책 규제(대출·세제)가 따라붙는 경우가 많았습니다.'
      : v >= 4
        ? '신고가 비중이 10%를 넘어서는지가 상승 확산 여부를 가르는 분기점입니다.'
        : '신저가 건수가 함께 줄어드는지 보면 바닥 통과 여부를 가늠할 수 있습니다.';

  const implication =
    v >= 10
      ? '목표 상급지가 이미 신고가 구간이면 갭은 계속 벌어집니다. 기다림의 비용이 커지는 국면입니다.'
      : v >= 4
        ? '상급지에서만 신고가가 나오는 시기라면 갭이 벌어지기 직전입니다.'
        : '신고가가 없는 시기가 갈아타기에 가장 유리합니다. 다만 매도도 어렵다는 점을 감안하세요.';

  return {
    level,
    meaning,
    trend,
    implication,
    position: Math.max(0, Math.min(1, v / 30)),
    scale: '0% ─ 10%(상승 확산) ─ 20%(과열) ─ 30%+',
  };
}

/** 거래량 — 가격보다 먼저 움직이는 선행 지표 */
export function volumeGuide(s: MarketSentiment): MetricGuide {
  const yoy = s.volumeYoy;

  const level =
    yoy >= 50
      ? '거래 급증'
      : yoy >= 15
        ? '거래 회복'
        : yoy >= -15
          ? '보합'
          : yoy >= -40
            ? '거래 감소'
            : '거래 절벽';

  const meaning =
    yoy >= 50
      ? '전년 대비 거래가 절반 이상 늘었습니다. 관망하던 수요가 한꺼번에 들어온 상태입니다.'
      : yoy >= 15
        ? '거래가 뚜렷하게 늘고 있습니다. 가격 상승은 보통 여기서 2~3개 분기 뒤에 따라옵니다.'
        : yoy >= -15
          ? '전년과 비슷한 수준입니다. 방향성을 판단하기 어려운 구간입니다.'
          : yoy >= -40
            ? '거래가 줄고 있습니다. 매수자와 매도자의 희망 가격 차이가 벌어진 상태입니다.'
            : '거래가 거의 멈췄습니다. 호가는 유지되지만 실제로 팔리지 않는 구간입니다.';

  const trend =
    yoy >= 15
      ? '거래량은 가격의 선행 지표입니다. 이 흐름이 이어지면 가격 상승이 뒤따를 가능성이 큽니다.'
      : yoy <= -15
        ? '거래량 감소가 먼저 오고 가격 하락이 뒤따르는 것이 일반적인 순서입니다.'
        : '거래량과 가격이 함께 정체된 구간입니다.';

  const implication =
    yoy >= 15
      ? '지금 매도하면 팔릴 가능성이 높습니다. 갈아타기 실행에 유리한 유동성 조건입니다.'
      : yoy <= -40
        ? '가격이 싸 보여도 내 집이 안 팔리면 갈아타기 자체가 성립하지 않습니다. 매도 우선순위를 높이세요.'
        : '매도 소요 기간을 넉넉히 잡고 계약 일정을 설계하세요.';

  return {
    level,
    meaning,
    trend,
    implication,
    position: Math.max(0, Math.min(1, (yoy + 50) / 130)),
    scale: '-50%(절벽) ─ 0%(보합) ─ +80%(급증)',
  };
}

/** 주간 가격 변동 */
export function priceMomentumGuide(s: MarketSentiment): MetricGuide {
  const v = s.weeklyPriceChange;

  const level =
    v >= 0.1
      ? '뚜렷한 상승'
      : v >= 0.02
        ? '완만한 상승'
        : v > -0.02
          ? '보합'
          : v > -0.1
            ? '완만한 하락'
            : '뚜렷한 하락';

  const meaning =
    v >= 0.1
      ? '주간 상승률이 0.1%를 넘으면 연 환산 5% 이상입니다. 상승 국면이 뚜렷합니다.'
      : v >= 0.02
        ? '주간으로는 작아 보여도 누적되면 의미 있는 상승입니다.'
        : v > -0.02
          ? '가격이 사실상 멈춰 있습니다.'
          : v > -0.1
            ? '완만한 조정입니다. 급매 위주로 가격이 형성됩니다.'
            : '주간 하락폭이 큽니다. 매물이 쌓이는 국면입니다.';

  const trend =
    '주간 지수는 표본이 작아 한 주 값보다 4주 연속 방향이 중요합니다. 방향이 바뀐 뒤 4주가 지나야 추세로 봅니다.';

  const implication =
    v >= 0.02
      ? '상급지가 먼저 오르는 구간이면 갭이 매주 벌어집니다.'
      : v <= -0.02
        ? '갭이 좁아지는 구간입니다. 하락장 시뮬레이션의 손익분기 하락률과 비교해 보세요.'
        : '지역별 편차를 확산 지도에서 직접 확인하는 편이 낫습니다.';

  return {
    level,
    meaning,
    trend,
    implication,
    position: Math.max(0, Math.min(1, (v + 0.2) / 0.4)),
    scale: '-0.2% ─ 0% ─ +0.2% (주간)',
  };
}

/** 종합 과열 점수 */
export function heatScoreGuide(s: MarketSentiment): MetricGuide {
  const v = s.heatScore;

  const level = v >= 75 ? '과열' : v >= 58 ? '회복' : v >= 42 ? '중립' : v >= 25 ? '관망' : '침체';

  const meaning =
    v >= 75
      ? '수급·신고가·거래량·모멘텀이 모두 상승을 가리킵니다. 과거 이 구간에서는 대출·세제 규제가 뒤따르는 경우가 많았습니다.'
      : v >= 58
        ? '네 지표 중 다수가 상승을 가리킵니다. 상급지부터 값이 오르고 하급지로 번지는 전형적인 회복 국면입니다.'
        : v >= 42
          ? '지표가 서로 엇갈립니다. 전체 방향보다 지역·단지별 편차가 큰 구간입니다.'
          : v >= 25
            ? '매수 심리가 위축돼 있습니다. 급매 위주로 거래가 이뤄집니다.'
            : '거래와 심리가 모두 얼어붙었습니다. 가격은 싸 보여도 매도가 어렵습니다.';

  const trend = `구성: 매매수급 40% · 신고가 비중 30% · 거래량 20% · 가격 모멘텀 10%. 현재 수급 ${s.supplyDemandIndex.toFixed(1)}, 신고가 ${s.newHighRatio.toFixed(1)}%, 거래량 YoY ${formatPct(s.volumeYoy, 0)}, 주간 ${formatPct(s.weeklyPriceChange, 2)}.`;

  const implication =
    v >= 58
      ? '기다릴수록 갭이 벌어지는 구간입니다. 자금이 준비됐다면 실행을 앞당기는 편이 유리합니다.'
      : v >= 42
        ? '방향을 기다리기보다 개별 단지의 실거래를 직접 추적하는 편이 낫습니다.'
        : '갭이 좁아지는 구간이지만 매도 난이도가 함께 올라갑니다. 매도 먼저 확정하는 전략이 안전합니다.';

  return {
    level,
    meaning,
    trend,
    implication,
    position: v / 100,
    scale: '0(침체) ─ 50(중립) ─ 100(극과열)',
  };
}
